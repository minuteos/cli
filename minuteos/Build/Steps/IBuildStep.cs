namespace MinuteOS.Cli.Build.Steps;

/// <summary>
/// A build step that can be contributed by components or the project.
/// Steps run at specific phases of the build pipeline and can
/// modify the build configuration, generate sources, transform
/// outputs, etc.
/// </summary>
public interface IBuildStep
{
    /// <summary>
    /// Unique name used to reference this step from component.yaml.
    /// </summary>
    string Name { get; }

    /// <summary>
    /// Default phase if not overridden by the step reference.
    /// </summary>
    BuildPhase DefaultPhase { get; }

    /// <summary>
    /// Execute the step.
    /// </summary>
    Task<StepResult> ExecuteAsync(StepContext context, CancellationToken cancellationToken);
}

public enum BuildPhase
{
    /// <summary>
    /// Before any compilation. Can modify configuration, generate sources.
    /// </summary>
    PreBuild,

    /// <summary>
    /// After all sources are compiled, before linking.
    /// </summary>
    PreLink,

    /// <summary>
    /// After linking the primary output.
    /// </summary>
    PostBuild,

    /// <summary>
    /// Executes the linked image (host directly, or via an emulator). NOT part of
    /// the build pipeline - resolved out-of-band by <c>minuteos run</c> / <c>test</c>.
    /// A target overrides this step to launch qemu/renode instead of running directly.
    /// </summary>
    Run,
}

/// <summary>
/// Context passed to build steps, providing access to the build
/// configuration, toolchain, and mutable build state.
/// </summary>
public class StepContext
{
    public required BuildConfiguration Configuration { get; init; }
    public required Toolchain Toolchain { get; init; }
    public required Microsoft.Extensions.Logging.ILogger Logger { get; init; }

    /// <summary>
    /// Configuration from the step reference in component.yaml.
    /// </summary>
    public Dictionary<string, string> StepConfig { get; init; } = new();

    /// <summary>
    /// Mutable build state that steps can contribute to.
    /// PreBuild steps can add generated sources, extra defines, etc.
    /// </summary>
    public BuildState State { get; init; } = new();

    /// <summary>Max parallel compilation jobs (used by the compile step).</summary>
    public int Parallelism { get; init; } = 1;

    /// <summary>When true, only warnings/errors are logged (per-suite test builds).</summary>
    public bool Quiet { get; init; }
}

/// <summary>
/// Mutable state accumulated across build steps.
/// </summary>
public class BuildState
{
    /// <summary>
    /// Additional source files generated by pre-build steps (e.g. a transpiler).
    /// These flow into the compile alongside the discovered sources.
    /// </summary>
    public List<SourceFile> GeneratedSources { get; } = [];

    /// <summary>
    /// Additional include directories contributed by steps (e.g. a transform
    /// step's generated-header dir). Merged into the compile's -I search path.
    /// </summary>
    public List<string> ExtraIncludeDirs { get; } = [];

    /// <summary>
    /// Additional defines contributed by steps.
    /// </summary>
    public List<string> ExtraDefines { get; } = [];

    /// <summary>
    /// Additional object files to include in linking (e.g. pre-compiled blobs).
    /// </summary>
    public List<string> ExtraObjects { get; } = [];

    /// <summary>
    /// Additional linker flags contributed by steps.
    /// </summary>
    public List<string> ExtraLinkFlags { get; } = [];

    /// <summary>
    /// Pipeline artifact slot: object files produced by the compile step and
    /// consumed by the link step.
    /// </summary>
    public List<string> Objects { get; } = [];

    /// <summary>
    /// Pipeline artifact slot: the linked primary image, set by the link step.
    /// </summary>
    public string? Image { get; set; }
}

public record StepResult(bool Success, string? Message = null)
{
    public static StepResult Ok(string? message = null) => new(true, message);
    public static StepResult Fail(string message) => new(false, message);
}
